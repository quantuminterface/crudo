def plot_sync_flag(
    raw_data, ramp_length, current_sync_delay=0, internal_delay=3, figure=None
):
    """
    Function to plot the sync flag in the flux ramp.
    The sync flag is used to separate the separate ramp periods from another.
    The LSB of the data is used as the sync flag.

    Note:
        The sync flag is generated by the ramp generation module and used as an input of the fluxramp demodulation module.
        Make sure that :func:`~firmware_modules.fluxrampdemod.FluxrampDemod.SetActSyncBypass` is activated.

    Args:
        raw_data: Raw data after channelizer of one channel
        ramp_length: Length of the flux ramp in samples
        current_sync_delay: Current delay of the demodulation defaults to 0
        ramp_count: Amount of ramps in data, defaults to 1
        internal_delay: Processing specific parameter, window module implies 3 cycles delay
    """
    # Get LSB as sync flag, nonezero gets indices of none zero values
    # Add intrinsic delay to first sync
    sync_flags = np.nonzero(np.real(raw_data) % 2)[0] + internal_delay

    data = np.abs(raw_data)

    # Scale Plot
    ymin, ymax = np.amin(data), np.amax(data)

    try:
        ctr = int(sync_flags[0] - current_sync_delay)
    except IndexError:
        ctr = 0
        print("Error: No Flag Found")

    if figure is None:
        _, ax = plt.figure()
    else:
        ax = figure

    # Plot ramp including sync flag
    ax.plot(np.arange(len(data)) - ctr, data)
    for idx in sync_flags:
        ax.plot([idx - ctr, idx - ctr], [ymin, ymax], color="r")

    # Plot discarded region

    # ax.title(
    #    f"current Delay: {current_sync_delay} samples, ramp length: {ramp_length}"
    # )
    ax.grid()


