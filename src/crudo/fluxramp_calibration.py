# Sine fit
def sine_func(x, a, b, c, d):
    return a * np.sin(b * x + c) + d


def find_modulation_freq(data, sample_rate, plot=False):
    fftax = None
    fitax = None
    if type(plot) is list:
        fftax = plot[0]
        fitax = plot[1]
    elif plot is not None:
        fftax = plot
        fitax = plot

    frequency_estimate, _ = signal_fft(
        data, sample_rate=sample_rate, height=0.001, window="rectangular", plot=fftax
    )

    phase_est = phase_estimate(data)

    modulation_frequency, modulation_offset = signal_fit(
        data, sample_rate, frequency_estimate, phase_est, fitax
    )

    return modulation_frequency, modulation_offset


def signal_fit(
    data,
    sample_rate,
    frequency_estimate=None,
    phase_estimate=None,
    plot=False,
    verbose=False,
):
    window_length = len(data)
    if frequency_estimate == None:
        frequency_estimate = sample_rate / 32
    frequency_estimate_normed = frequency_estimate / sample_rate * (2 * np.pi)
    p0 = [
        (max(abs(data)) - min(abs(data))) / 2,
        abs(frequency_estimate_normed),
        phase_estimate,
        np.mean(abs(data)),
    ]
    # TODO without phase needs negative freqs. gradient search does not work!
    bounds = [
        [0, 0, 0, min(abs(data))],
        [max(abs(data)), sample_rate / 4, 2 * np.pi, max(abs(data))],
    ]
    if verbose:
        print(f"Guess: {p0}")

    params, params_cov = optimize.curve_fit(
        lambda x, pha: sine_func(x, p0[0], p0[1], pha, p0[-1]),  # Fit phase first
        np.linspace(0, window_length - 1, window_length),
        np.abs(data),
        p0=p0[2],
        bounds=[0, 2 * np.pi],
        maxfev=5e4,
    )
    p0[2] = params[0]

    params, params_cov = optimize.curve_fit(
        sine_func,
        np.linspace(0, window_length - 1, window_length),
        np.abs(data),
        p0=p0,
        bounds=bounds,
        maxfev=5e4,
    )
    if verbose:
        print(f"Params: {params}")
    fitted_frequency = (params[1] / (2 * np.pi)) * sample_rate
    if plot:
        if type(plot) is not bool:
            plt.sca(plot)
        plt.plot(data, ".", label="data")
        plt.plot(
            np.linspace(0, window_length - 1, window_length * 10),
            sine_func(
                np.linspace(0, window_length - 1, window_length * 10),
                *params,
            ),
            label=f"Sine fit, f = {fitted_frequency/1e3:3.3f} kHz",
        )
        plt.plot(
            np.linspace(0, window_length - 1, window_length * 10),
            sine_func(
                np.linspace(0, window_length - 1, window_length * 10),
                *p0,
            ),
            label=f"Guess f = {(p0[1] / (2 * np.pi)) * sample_rate/1e3:3.3f} kHz",
        )
        plt.legend()
        if type(plot) is bool:
            plt.show()

    return fitted_frequency, params[3]


def phase_estimate(data):
    pkx, _ = signal.find_peaks(data, height=np.median(data))
    if len(pkx) > 1:
        return (-(0.5 + pkx[0] / (pkx[1] - pkx[0])) * np.pi) % np.pi
    # TODO Percentile?
    # TODO Always use the latter?
    temp = np.abs(data - np.median(data))
    pkx, _ = signal.find_peaks(temp, height=np.median(temp))
    if len(pkx) > 1:
        return (-(0.25 + pkx[0] / (pkx[1] - pkx[0])) * np.pi) % np.pi
    return 0 if abs(data[1]) - abs(data[0]) > 0 else np.pi


def signal_fft(
    data,
    sample_rate,
    height=None,
    window="rectangular",
    current_conf=None,
    flim=(0, None),
    plot=True,
):
    """
    Compute the modulation frequencies from the FFT of raw traces.
    For multiple traces (passed as numpy 2d-array) the FFT spectra are averaged.

    Args:
        sliced_traces: input data
        sample_rate (int): sample_rate of the input data
        height (float): threshold of the frequeny to be considered as modulation
        window (String): Window to be used within the FFT
        current_conf: ??
        flim: ??
    """
    # TODO Why DSB?
    # TODO if not working, try padding/repeating
    # TODO if not working, count peaks/transitions
    f_space, p_spec = signal.periodogram(data, sample_rate, window, scaling="density")
    # FFT is averaged if 2d-array is passed

    if plot:
        if type(plot) is bool:
            plt.figure(figsize=(10, 7))
        else:
            plt.sca(plot)
        plt.plot(1e-6 * f_space, p_spec)
        if height is None:
            print("Pass a height to specify the peak threshold")
        else:
            plt.semilogy(1e-6 * f_space, height * np.ones(len(f_space)))
        plt.xlim(flim)
        plt.xlabel("frequency in MHz")
        plt.ylabel("power spectral density")

        # if not current_conf is None:
        #    plot_frequency_config(current_conf, ax[1])
        if type(plot) is bool:
            plt.show()

    peak_indices, _ = signal.find_peaks(p_spec, height=height)
    peak_freq = [f_space[idx] for idx in peak_indices]
    peak_ampl = p_spec[5]

    # print(f"Peak freq: {peak_freq[0]}, index {peak_indices[0]}")
    peak_freq = sorted(np.abs(peak_freq))
    if peak_freq[0] < 1e3:
        del peak_freq[0]
    if len(peak_freq) == 0:
        peak_freq = None
    else:
        peak_freq = peak_freq[0]
    return peak_freq, peak_ampl


