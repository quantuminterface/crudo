def slice_at_sync(raw_data, samples_per_ramp, add_sync_latency=1):
    """
    Slices raw data based on the sync signal encoded in the least significant bit (of real part)

    Args:
        raw_data : (int) data array with LSB representing the sync signal
        samples_per_ramp : sample count between two sync signals
        add_sync_latency : additional sync latency (e.g. due to windowing in hardware), defaults to 1

    Returns:
        numpy 2d-array of sliced data traces
    """
    sync_flags = np.nonzero(np.real(raw_data) % 2)[0] + add_sync_latency
    samples_per_ramp = int(round(samples_per_ramp))
    slice_count = len(raw_data) // samples_per_ramp - 1
    for idx, diff in enumerate(np.diff(sync_flags)):
        if diff != samples_per_ramp:
            print(
                f"Warning: Only {idx} / {slice_count} possible Slices used due to mismatch in Spacing. Diff should be {samples_per_ramp}, but is {diff}"
            )
            slice_count = idx
            break

    # avoid indexing errors
    if slice_count > len(sync_flags) - 1 or sync_flags[slice_count] >= len(raw_data):
        slice_count -= 1

    # output a numpy 2d-array
    return raw_data[sync_flags[0] : sync_flags[slice_count]].reshape(
        slice_count, samples_per_ramp
    )


def fit_modulation_frequencies(
    data,
    sample_rate,
    fit_width,
    peak_height,
    window="blackmanharris",
    flim=(0, None),
):
    """
    fit the spectral peaks to get the modulation/carrier frequencies

    Args:
        data          : bypassed raw data (real), sliced into a 2d-array
        sample_rate   : sample rate of the traces
        fit_width     : number of samples around the peak contributing to the fit
        peak_height   : threshold for find_peaks
        window        : window function used for the FFT

    Returns
        mu : the center frequencies of the fit
    """
    # Generate the Spectrum and find peaks
    f_space, p_spec = ipe_scipy.normalized_fft(data, 1 / sample_rate, window)
    peak_indices, _ = signal.find_peaks(
        p_spec, height=peak_height, distance=fit_width // 2
    )

    _, ax = plt.subplots(1, 1, figsize=(20, 10))
    ax.plot(f_space * 1e-6, p_spec, color="b")
    flim = ax.set_xlim(flim)
    ax.set_xlabel("frequency in MHz")
    ax.set_ylabel("spectral density (a. u.)")

    # Fit the gaussian function to each peak and save the parameters
    number_peaks = len(peak_indices)
    ampl = np.zeros(number_peaks)
    mu = np.zeros(number_peaks)
    sigma = np.zeros(number_peaks)

    x_space = np.linspace(flim[0], flim[1], 300)
    for j, peak_idx in enumerate(peak_indices):
        try:
            ampl[j], mu[j], sigma[j] = ipe_scipy.fit_gaussian(
                f_space, p_spec, peak_idx, fit_width
            )
        except RuntimeError:
            print(f"Fitting failed for Peak at {1e-6 * f_space[peak_idx]:.2f} MHz")
            ampl[j], mu[j], sigma[j] = np.nan, np.nan, np.nan
            continue

        ax.plot(
            x_space,
            ipe_scipy.gaussian(x_space * 1e6, ampl[j], mu[j], sigma[j]),
            color="r",
            alpha=0.5,
        )

    plt.show()

    return mu


def show_frequency_drift(
    sliced_traces,
    sample_rate,
    subframe_length,
    subframe_count,
    fit_width,
    peak_height,
    peak_count,
    window="blackmanharris",
):
    """
    Investigate the modulation/carrier frequencies in the time frame of one ramp.
    Use multiple traces for higher accurracy.
    The FFT is performed over multiple overlapping subframes, fitting the peaks for each time section.
    The relative change of modulation frequencies is plotted

    Args:
        sliced_traces   : bypassed raw data (real), sliced into a 2d-array
        sample_rate     : sample rate of raw data
        subframe_length : sample count of each subframe, must be smaller than length of a sliced trace
        subframe_count  : number of subframes
        fit_width       : number of samples around the peak contributing to the fit
        peak_height     : threshold for find_peaks
        peak_count      : number of carrier/modulation frequencies in the signal
        window          : window function used for the FFT
        debug           : plots the spectra to give an estimation on the peak_height
    """
    # Define subframe intervals
    half_frame = subframe_length // 2
    trace_length = sliced_traces.shape[-1]
    center_indices = np.linspace(
        half_frame, trace_length - half_frame, subframe_count, endpoint=True, dtype=int
    )

    # Initialize data and parameter arrays
    # p_spec_subframes = np.zeros((subframe_count, half_frame - 1))
    mod_frequencies = np.zeros((subframe_count, peak_count))

    # Prepare Plot
    _, ax = plt.subplots(1, 1, figsize=(20, 10))
    if peak_height is None:
        ax.set_xlabel("frequency in MHz")
        ax.set_ylabel("power spectral density in arb. units")
        colors = plt.get_cmap("inferno")(np.linspace(0, 1, subframe_count))
    else:
        ax.set_xlabel("center of subframe in timeframe of a flux ramp in µs")
        ax.set_ylabel("relative change of frequency")
        colors = plt.get_cmap("inferno")(
            np.linspace(0.1, 0.9, peak_count, endpoint=True)
        )
        frame_spacing = (center_indices[1] - center_indices[0]) / sample_rate
        dot_shift = frame_spacing / (peak_count + 1) / 2

    # Generate FFTs of subframes
    for j, c_idx in enumerate(center_indices):
        # f_space, p_spec_subframes[j] = ipe_scipy.normalized_fft(
        f_space, p_spec = ipe_scipy.normalized_fft(
            input_signal=window[:, c_idx - half_frame : c_idx + half_frame],
            d_t=1 / sample_rate,
            window_name=window,
        )

        if peak_height is None:
            ax.plot(f_space * 1e-6, p_spec, color=colors[j], label=f"subframe {j}")
            continue

        peak_indices, _ = signal.find_peaks(
            p_spec, height=peak_height, distance=fit_width // 2
        )
        for k, p_idx in enumerate(sorted(peak_indices)):
            try:
                _, mod_frequencies[j, k], sigma = ipe_scipy.fit_gaussian(
                    f_space, p_spec, p_idx, fit_width
                )
            except RuntimeError:
                print(
                    f"Fitting failed for peak at {f_space[p_idx] * 1e-6} MHz in subframe {j}"
                )
                mod_frequencies[j, k] = np.nan

            if j == 0:
                label = f"$f_0 = {mod_frequencies[j, k] * 1e-6}$ MHz"
            else:
                label = None

            # generate horizontally shifted errorbars
            ax.errorbar(
                x=(c_idx / sample_rate + dot_shift * (k - peak_count // 2)) * 1e6,
                y=mod_frequencies[j, k] / mod_frequencies[0][k],
                yerr=sigma / mod_frequencies[0][k],
                marker="o",
                color=colors[k],
                label=label,
            )

    plt.legend(loc="best")
    plt.show()
